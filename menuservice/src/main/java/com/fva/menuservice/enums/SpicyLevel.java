package com.fva.menuservice.enums;

/**
 * Represents the spice level of a menu item.
 */
public enum SpicyLevel {

    /**
     * No or very little spice.
     */
    MILD,

    /**
     * Moderate spice.
     */
    MEDIUM,

    /**
     * Hot and spicy.
     */
    HOT,

    /**
     * Extremely spicy.
     */
    EXTRA_HOT
}