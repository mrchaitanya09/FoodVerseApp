package com.fva.restaurentservice.enums;

/**
 * Represents the different types of images associated with a restaurant.
 */
public enum ImageType {

    /**
     * Restaurant logo displayed across the application.
     */
    LOGO,

    /**
     * Banner/Cover image displayed on the restaurant details page.
     */
    BANNER,

    /**
     * Gallery images showcasing the restaurant ambiance and food.
     */
    GALLERY,

    /**
     * Menu image uploaded by the restaurant.
     */
    MENU
}